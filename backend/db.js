function resolveDbProvider() {
  if (isTestRun) {
    return 'sqlite';
  }

  const hasPostgresConnection = Boolean(process.env.SUPABASE_DB_URL || process.env.DATABASE_URL);
  if (process.env.VERCEL && hasPostgresConnection) {
    return 'postgres';
  }

  const requested = (process.env.DB_PROVIDER || 'sqlite').toLowerCase();
  if (requested === 'postgres' && !hasPostgresConnection) {
    return 'sqlite';
  }

  return requested;
}

