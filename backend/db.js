function ensureDb() {
  if (!sqlite3) {
    throw new Error('SQLite is unavailable in this environment. Configure SUPABASE_DB_URL or DATABASE_URL and set DB_PROVIDER=postgres for serverless deployments.');
  }

  if (!db) {
    db = new sqlite3.Database(dbPath);
  }
  return db;
}

function getPostgresPool() {
  if (!postgresPool) {
    const connectionString = process.env.SUPABASE_DB_URL || process.env.DATABASE_URL;
    if (!connectionString) {
      throw new Error('Missing SUPABASE_DB_URL or DATABASE_URL. Configure the Postgres connection string before switching DB_PROVIDER to postgres.');
    }

    postgresPool = new Pool({
      connectionString,
      ssl: { rejectUnauthorized: false },
    });

    postgresPool.on('error', (err) => {
      console.warn('Postgres pool error detected; falling back to SQLite.', err.message);
      DB_PROVIDER = 'sqlite';
      postgresPool = null;
    });
  }

  return postgresPool;
}

async function ensurePostgresReady() {
  if (DB_PROVIDER !== 'postgres') {
    return false;
  }

  try {
    const pool = getPostgresPool();
    await pool.query('SELECT 1');
    return true;
  } catch (error) {
    console.warn('Postgres unavailable, falling back to SQLite.', error.message);
    DB_PROVIDER = 'sqlite';
    postgresPool = null;
    return false;
  }
}

function convertSqlForPostgres(sql, params = []) {
  let normalized = sql.replace(/INSERT\s+OR\s+IGNORE\s+INTO/gi, 'INSERT INTO');
  if (/INSERT\s+INTO/gi.test(normalized) && !/ON\s+CONFLICT/gi.test(normalized) && /INSERT\s+OR\s+IGNORE/gi.test(sql)) {
    normalized = `${normalized} ON CONFLICT DO NOTHING`;
  }

  normalized = normalized.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  normalized = normalized.replace(/AUTOINCREMENT/gi, 'GENERATED BY DEFAULT AS IDENTITY');

  let index = 0;
  const converted = normalized.replace(/\?/g, () => {
    index += 1;
    return `$${index}`;
  });

  return { sql: converted, params };
}

function createPgCompatibleDb() {
  return {
    get(sql, params, callback) {
      if (typeof params === 'function') {
        callback = params;
        params = [];
      }

      get(sql, params)
        .then((row) => callback(null, row))
        .catch((err) => callback(err, null));
    },
    all(sql, params, callback) {
      if (typeof params === 'function') {
        callback = params;
        params = [];
      }

      all(sql, params)
        .then((rows) => callback(null, rows))
        .catch((err) => callback(err, null));
    },
    run(sql, params, callback) {
      if (typeof params === 'function') {
        callback = params;
        params = [];
      }

      run(sql, params)
        .then((result) => callback(null, result))
        .catch((err) => callback(err, null));
    },
    close(callback) {
      closeDb()
        .then(() => callback && callback())
        .catch((err) => callback && callback(err));
    },
  };
}

async function run(sql, params = []) {
  if (DB_PROVIDER === 'postgres') {
    const ready = await ensurePostgresReady();
    if (!ready) {
      return new Promise((resolve, reject) => {
        ensureDb().run(sql, params, function onRun(err) {
          if (err) {
            reject(err);
            return;
          }
          resolve({ id: this.lastID, changes: this.changes });
        });
      });
    }

    const { sql: query, params: values } = convertSqlForPostgres(sql, params);
    const result = await getPostgresPool().query(query, values);
    return { id: result.rows[0]?.id ?? null, changes: result.rowCount ?? 0 };
  }

  return new Promise((resolve, reject) => {
    ensureDb().run(sql, params, function onRun(err) {
      if (err) {
        reject(err);
        return;
      }
      resolve({ id: this.lastID, changes: this.changes });
    });
  });
}

async function get(sql, params = []) {
  if (DB_PROVIDER === 'postgres') {
    const ready = await ensurePostgresReady();
    if (!ready) {
      return new Promise((resolve, reject) => {
        ensureDb().get(sql, params, (err, row) => {
          if (err) {
            reject(err);
            return;
          }
          resolve(row);
        });
      });
    }

    if (/^PRAGMA\s+table_info/i.test(sql)) {
      const tableMatch = sql.match(/PRAGMA\s+table_info\s*\(\s*['"]?([A-Za-z0-9_]+)['"]?\s*\)/i);
      if (tableMatch) {
        const tableName = tableMatch[1];
        const result = await getPostgresPool().query(
          `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = 'public' AND table_name = $1 ORDER BY ordinal_position`,
          [tableName]
        );
        return result.rows[0] ? result.rows : result.rows;
      }
    }

    const { sql: query, params: values } = convertSqlForPostgres(sql, params);
    const result = await getPostgresPool().query(query, values);
    return result.rows[0] || null;
  }

  return new Promise((resolve, reject) => {
    ensureDb().get(sql, params, (err, row) => {
      if (err) {
        reject(err);
        return;
      }
      resolve(row);
    });
  });
}

async function all(sql, params = []) {
  if (DB_PROVIDER === 'postgres') {
    const ready = await ensurePostgresReady();
    if (!ready) {
      return new Promise((resolve, reject) => {
        ensureDb().all(sql, params, (err, rows) => {
          if (err) {
            reject(err);
            return;
          }
          resolve(rows);
        });
      });
    }

    if (/^PRAGMA\s+table_info/i.test(sql)) {
      const tableMatch = sql.match(/PRAGMA\s+table_info\s*\(\s*['"]?([A-Za-z0-9_]+)['"]?\s*\)/i);
      if (tableMatch) {
        const tableName = tableMatch[1];
        const result = await getPostgresPool().query(
          `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = 'public' AND table_name = $1 ORDER BY ordinal_position`,
          [tableName]
        );
        return result.rows;
      }
    }

    const { sql: query, params: values } = convertSqlForPostgres(sql, params);
    const result = await getPostgresPool().query(query, values);
    return result.rows;
  }

  return new Promise((resolve, reject) => {
    ensureDb().all(sql, params, (err, rows) => {
      if (err) {
        reject(err);
        return;
      }
      resolve(rows);
    });
  });
}

